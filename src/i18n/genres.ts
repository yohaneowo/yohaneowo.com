export function genreName(genre: string, lang: Locale) {
  return lang === "en" ? (ENGLISH[genre] ?? genre) : (ANILIST_GENRES_ZH[genre] ?? genre);
}

export function tagName(tag: string, lang: Locale) {
  return lang === "en" ? tag : (TAGS_ZH[tag] ?? tag);
}

export function sourceName(source: string, lang: Locale) {
  const names = SOURCE[source];
  return names ? names[lang === "en" ? 1 : 0] : null;
}
